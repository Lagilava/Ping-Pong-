const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
let focused = false;
const panel = {hidden:true, querySelector(){ return {focus(){focused=true;}}; }};
const text = {textContent:''}, go = {textContent:''};
const menu = {querySelector:s=>s==='#pauseConfirm'?panel:null, querySelectorAll:()=>[]};
const nodes = {pauseMenu:menu,pauseConfirm:panel,pauseConfirmText:text,pauseConfirmGo:go};
const document = {getElementById:id=>nodes[id],querySelector:()=>({focus(){}}),activeElement:{}};
const context=vm.createContext({window:{},document,Math,clearTimeout(){},setTimeout(){throw Error('Confirmation must not expire');}});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../game/js/core/game.js'),'utf8'),context);
const game=Object.create(context.window.Game.prototype);
let quits=0,restarts=0;
game.returnToMenu=()=>quits++;
game.restartMatch=()=>restarts++;
game.handlePauseAction('quit',{dataset:{act:'quit'}});
assert.equal(quits,0,'requesting quit cannot exit immediately');
assert.equal(panel.hidden,false);
assert.equal(game._pendingPauseAction,'quit');
assert.equal(focused,true,'safe cancel choice receives focus');
game.handlePauseAction('cancel-confirm');
assert.equal(panel.hidden,true);
game.handlePauseAction('confirm-pending');
assert.equal(quits,0,'cancelled confirmation cannot execute later');
game.handlePauseAction('quit',{dataset:{act:'quit'}});
game.handlePauseAction('confirm-pending');
assert.equal(quits,1);
assert.equal(panel.hidden,true);
game.handlePauseAction('confirm-pending');
assert.equal(quits,1,'confirmation executes only once');
game.handlePauseAction('restart',{dataset:{act:'restart'}});
assert.equal(restarts,0);
assert.match(go.textContent,/Restart/);
game.handlePauseAction('confirm-pending');
assert.equal(restarts,1);
let hostRestarts=0;
game.net={role:'guest',hostStart(){hostRestarts++;}};
game.handlePauseAction('restart',{dataset:{act:'restart'}});
game.handlePauseAction('confirm-pending');
assert.equal(hostRestarts,0,'guest cannot restart the host match');
game.net.role='host';
game.handlePauseAction('restart',{dataset:{act:'restart'}});
game.handlePauseAction('confirm-pending');
assert.equal(hostRestarts,1);
let helped;
context.window.ModeTutorial={open(mode){helped=mode;}};
game.gameMode='zombie';game.handlePauseAction('help');
assert.equal(helped,'zombie','help opens the current mode');
console.log('Pause cancel/confirm, single execution, online ownership and contextual help passed.');
