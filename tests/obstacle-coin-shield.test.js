const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = vm.createContext({window: {}});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../game/js/modes/obstacle-arcade.js'), 'utf8'), context);
function arcade(extra = {}) {
    const game = {width: 1000, height: 600, showNotification() {}, ...extra};
    const result = new context.window.ObstacleArcade(game);
    result.syncHud = () => {};
    return result;
}
const a = arcade();
a.addCoins('player', 3, 700, 200);
assert.equal(a.wallet.player, 3, 'show pickup before spending');
assert(a.hasShield('player'), 'flight must not delay goal protection');
a.updateCoinFlights(0.3);
assert.equal(a.wallet.player, 3);
a.updateCoinFlights(0.3);
assert.equal(a.wallet.player, 2, 'one new shield costs exactly one coin');
assert(a.chargeFlare.player > 0 && a.coinSpent.player > 0);
a.updateCoinFlights(1);
assert.equal(a.wallet.player, 2, 'settled flights cannot double-charge');
a.addCoins('player', 1, 600, 200);
a.updateCoinFlights(1);
assert.equal(a.wallet.player, 3, 'collecting with an active shield banks the coin');
a.onShieldBlock('player');
assert.equal(a.shield.player, 0, 'one goal consumes the shield, without stacking');
a.addCoins('player', 1, 600, 200);
a.updateCoinFlights(1);
assert.equal(a.wallet.player, 3, 'a replacement shield spends one coin');
a.addCoins('ai', 1, 300, 200);
assert.equal(a.wallet.ai, 0, 'solo AI gets no rewards');
const multiplayer = arcade({isMultiplayer: true});
multiplayer.addCoins('ai', 1, 300, 200);
multiplayer.updateCoinFlights(1);
assert.equal(multiplayer.wallet.ai, 0);
assert.equal(multiplayer.shield.ai, 1);
assert.equal(multiplayer.shield.player, 0);
const guest = arcade({net: {role: 'guest'}});
guest.wallet.ai = 4;
guest.addCoins('ai', 1, 200, 200);
assert.equal(guest.wallet.ai, 4, 'guests must not author rewards');
guest.queueCoinFlights('ai', 1, 200, 200, true, true);
guest.updateCoinFlights(1);
assert.equal(guest.wallet.ai, 4, 'remote cosmetics cannot spend authoritative money');
assert(guest.chargeFlare.ai > 0);
const capped = arcade();
for (let i = 0; i < 40; i++) capped.addCoins('player', 1, 200, 200);
assert(capped.coinFlights.length <= 32);
capped.onShieldBlock('player');
capped.addCoins('player', 1, 200, 200);
capped.updateCoinFlights(2);
assert.equal(capped.wallet.player, 39, 'bounded cosmetics must still settle both shield payments');
capped.addCoins('player', 1, 200, 200);
capped.reset();
capped.updateCoinFlights(2);
assert.equal(capped.wallet.player, 0);
assert.equal(capped.coinFlights.length, 0);
assert.equal(capped.chargeFlare.player, 0);
console.log('Obstacle coin payment, shield protection, multiplayer ownership and reset passed.');
